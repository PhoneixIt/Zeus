/**
 * THE SUMMARY BOUNDARY.
 *
 * `Summarizer.generate(input) -> result`. That is the whole interface.
 *
 * THIS IS NOT AI REASONING, and nothing here pretends otherwise. The implementation below is a
 * deterministic content generator: it counts entries, groups them by extension, and formats
 * them. It does not understand the files, does not infer meaning, and says so in its output via
 * `provenance`.
 *
 * WHY THE INTERFACE MATTERS ANYWAY
 *
 * Because the substitution has to be free. When a model is added later it implements this
 * interface and nothing else changes - not the tool that calls it, not the mission, not the
 * verifier. If summarisation logic had been written inline inside the filesystem tool, adding
 * a model would mean rewriting the tool, and the tool is the part with the containment checks.
 *
 * So the rule for this module: it may know about file EXTENSIONS and NAMES, and nothing else. It
 * receives a listing, never a path to read, so it cannot read a file it was not given.
 */

export interface FolderEntry {
  readonly name: string
  readonly kind: 'file' | 'directory'
  readonly bytes?: number
  /** Lower-cased extension without the dot. Empty for a directory or an extensionless file. */
  readonly extension: string
}

export interface SummaryInput {
  /** For the record. Not used to read anything - the listing below is the whole input. */
  readonly folderLabel: string
  readonly entries: readonly FolderEntry[]
}

export interface SummaryResult {
  readonly text: string
  readonly entryCount: number
  readonly fileCount: number
  readonly directoryCount: number
  /**
   * Which implementation produced this.
   *
   * Carried in the output rather than inferred by the caller, so a record of a mission states
   * whether its summary came from a deterministic generator or a model. A summary that cannot
   * say where it came from cannot be weighed by whoever reads it.
   */
  readonly provenance: 'deterministic' | 'model'
  /** What the generator actually did, so its limits are visible in the artefact. */
  readonly method: string
}

export interface Summarizer {
  readonly name: string
  generate(input: SummaryInput): Promise<SummaryResult>
}

/** Extension a file is counted under. Deliberately a plain string operation. */
function extensionOf(name: string, kind: 'file' | 'directory'): string {
  if (kind === 'directory') return ''
  const dot = name.lastIndexOf('.')
  if (dot <= 0 || dot === name.length - 1) return ''
  return name.slice(dot + 1).toLowerCase()
}

/**
 * The deterministic generator.
 *
 * What it does: counts entries, groups files by extension, lists the largest files, formats
 * the result as markdown.
 *
 * What it does NOT do: read any file, infer what the folder is for, or write prose about
 * meaning. A folder of invoices and a folder of cat photographs produce structurally identical
 * summaries, and that limitation is stated in the artefact itself rather than hidden.
 */
export class StructuredSummarizer implements Summarizer {
  readonly name = 'structured-deterministic'

  async generate(input: SummaryInput): Promise<SummaryResult> {
    const entries = input.entries
    const files = entries.filter((e) => e.kind === 'file')
    const dirs = entries.filter((e) => e.kind === 'directory')

    const byExt = new Map<string, number>()
    for (const f of files) {
      const key = f.extension || '(no extension)'
      byExt.set(key, (byExt.get(key) ?? 0) + 1)
    }
    const groups = [...byExt.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))

    const largest = [...files]
      .filter((f) => typeof f.bytes === 'number')
      .sort((a, b) => (b.bytes ?? 0) - (a.bytes ?? 0))
      .slice(0, 5)

    const lines: string[] = []
    lines.push(`# Contents of ${input.folderLabel}`)
    lines.push('')
    lines.push(`- ${entries.length} entries total: ${files.length} file(s), ${dirs.length} folder(s)`)
    if (groups.length) {
      lines.push(`- by extension: ${groups.map(([k, n]) => `${k} (${n})`).join(', ')}`)
    } else {
      lines.push('- no files to classify')
    }
    if (largest.length) {
      lines.push('')
      lines.push('## Largest files')
      for (const f of largest) lines.push(`- ${f.name} - ${f.bytes} bytes`)
    }
    if (dirs.length) {
      lines.push('')
      lines.push('## Folders')
      for (const d of dirs) lines.push(`- ${d.name}/`)
    }
    lines.push('')
    lines.push('---')
    lines.push('Generated by a deterministic content generator. It counted names, extensions')
    lines.push('and sizes; it did not read file contents and makes no claim about meaning.')

    return {
      text: lines.join('\n'),
      entryCount: entries.length,
      fileCount: files.length,
      directoryCount: dirs.length,
      provenance: 'deterministic',
      method: 'counted entries, grouped files by extension, listed the five largest',
    }
  }
}

/** Builds a listing from names. Shared by tools and tests so both see the same shape. */
export function entriesFrom(names: readonly string[], sizeOf: (name: string) => number | undefined): FolderEntry[] {
  return names.map((name) => {
    const isDir = !name.includes('.')
    // A name with a dot is not proof of a file, so the caller supplies the real kind via
    // sizeOf returning undefined for a directory. Kept explicit rather than guessed.
    const kind: 'file' | 'directory' = sizeOf(name) === undefined && isDir ? 'directory' : 'file'
    return {
      name,
      kind,
      bytes: kind === 'file' ? sizeOf(name) : undefined,
      extension: extensionOf(name, kind),
    }
  })
}